#!/usr/bin/env node
/**
 * Scan public/content/uh-psych and emit a typed education manifest for the hub UI.
 * Run after adding PDFs/handouts: node scripts/generate-education-manifest.mjs
 */
import fs from "node:fs";
import path from "node:path";

const ROOT = path.resolve("public/content/uh-psych");
const OUT = path.resolve("src/lib/v2/programs/uh-education-manifest.ts");

const CATEGORIES = [
  {
    id: "landmark-articles",
    dir: "landmark-articles",
    title: "Landmark articles",
    description: "Seminal papers by diagnosis and topic — program reading list.",
  },
  {
    id: "psychopharmacology",
    dir: "psychopharmacology",
    title: "Psychopharmacology",
    description: "Quick-reference charts and fact sheets for inpatient and outpatient prescribing.",
  },
  {
    id: "patient-handouts",
    dir: "patient-handouts",
    title: "For patients",
    description: "Handouts and community resources to share with patients and families.",
  },
  {
    id: "core-readings",
    dir: "core-readings",
    title: "Core readings",
    description: "Foundational texts for capacity, ethics, and clinical reasoning.",
  },
  {
    id: "electives",
    dir: "electives",
    title: "Electives",
    description: "Master elective catalog spreadsheet — locations, faculty, and requirements.",
  },
];

const SKIP_DIRS = new Set(["schedules"]);
const CONTENT_BASE = "/content/uh-psych";

function slugify(value) {
  return value
    .toLowerCase()
    .replace(/['"]/g, "")
    .replace(/[^a-z0-9]+/g, "-")
    .replace(/^-+|-+$/g, "")
    .slice(0, 80);
}

function titleFromFilename(filename) {
  const base = filename.replace(/\.[^.]+$/, "");
  return base.replace(/[_-]+/g, " ").replace(/\s+/g, " ").trim();
}

function walkFiles(dir, relativePrefix = "") {
  if (!fs.existsSync(dir)) return [];
  const entries = fs.readdirSync(dir, { withFileTypes: true }).sort((a, b) => a.name.localeCompare(b.name));
  const files = [];
  for (const entry of entries) {
    const rel = relativePrefix ? `${relativePrefix}/${entry.name}` : entry.name;
    const abs = path.join(dir, entry.name);
    if (entry.isDirectory()) {
      if (SKIP_DIRS.has(entry.name)) continue;
      files.push(...walkFiles(abs, rel));
    } else if (entry.isFile()) {
      files.push(rel);
    }
  }
  return files;
}

function subcategoryFromPath(relativePath) {
  const parts = relativePath.split("/");
  if (parts.length <= 1) return undefined;
  return parts.slice(0, -1).join(" / ");
}

const categories = CATEGORIES.map((cat) => {
  const dir = path.join(ROOT, cat.dir);
  const files = walkFiles(dir);
  const documents = files.map((rel) => {
    const filename = path.basename(rel);
    const hrefRel = rel.split("/").map(encodeURIComponent).join("/");
    const subcategory = subcategoryFromPath(rel);
    const id = slugify(`${cat.id}-${rel}`);
    const doc = {
      id,
      title: titleFromFilename(filename),
      href: `${CONTENT_BASE}/${cat.dir}/${hrefRel}`,
      filename,
    };
    if (subcategory) doc.subcategory = subcategory;
    return doc;
  });
  return {
    id: cat.id,
    title: cat.title,
    description: cat.description,
    documents,
  };
}).filter((c) => c.documents.length > 0);

const totalDocs = categories.reduce((n, c) => n + c.documents.length, 0);

const header = `/**
 * AUTO-GENERATED by scripts/generate-education-manifest.mjs — do not edit by hand.
 * ${totalDocs} documents across ${categories.length} categories.
 */
`;

const body = `export type EducationDocument = {
  id: string;
  title: string;
  href: string;
  filename: string;
  description?: string;
  subcategory?: string;
  tags?: string[];
};

export type EducationCategory = {
  id: string;
  title: string;
  description: string;
  documents: EducationDocument[];
};

export const EDUCATION_CATEGORIES: EducationCategory[] = ${JSON.stringify(categories, null, 2)};
`;

fs.writeFileSync(OUT, header + body);
console.log(`Wrote ${OUT} (${totalDocs} documents, ${categories.length} categories)`);
